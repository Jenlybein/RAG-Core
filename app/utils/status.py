"""文档状态：整数常量，1 成功 / 2 失败 / 3 索引中 / 4 排队中。

用整数不用字符串：省空间、免拼写错误、前端可直接 status === 3。
代码里一律写 ``DocumentStatus.PROCESSING`` / ``DocumentStatus.QUEUED``，不要写裸的 3 / 4。

## 为什么 3 与 4 要分开（ADR-0034 决策一）

三态时那个「处理中」同时盖着三件事：已排队没开工（没有租约）、真的在跑（租约在窗口内）、
跑崩了（租约过期）。用户看到同一个词，分不出「再等一分钟」和「永远等不到」，而三件事的
处置完全不同——前者允许撤回（删掉、重新提交），后两者必须等或救。

拆开之后两者的唯一区别是**在谁手上**，不是进度：

* ``QUEUED``（4）：已经被收下、还没被任何 Worker 接走。判据是**没有租约**（也不该有），
  只由入队侧写（上传、重建、建版本、回滚的准备步骤）。
* ``PROCESSING``（3）：**此刻**有某个 Worker 拿着这一篇在跑。**唯一权威证据是租约**
  （``index_claimed_at`` 落在租约窗口内），只由 Worker 在抢占时写。租约过期即视为
  「没人跑」——不管库里那一行写着什么，语义上它就是排队中。

于是「``3`` 且租约为空」是一种**迁移期兼容形状**：迁移会把存量这样的行改成 4
（``migrations/versions/*_queue_document_status.py``），可抢占条件仍然保留这一支，
以免迁移之前 / 迁移过程中的读侧把它当成「在跑」。
"""


class DocumentStatus:
    """文档处理状态常量。"""

    SUCCESS = 1
    FAILED = 2
    #: 索引中：租约有效才算（见模块文档）。
    PROCESSING = 3
    #: 排队中：已收下、没有租约；可以删除（撤回排队）与重新提交（替换排队）。
    QUEUED = 4
