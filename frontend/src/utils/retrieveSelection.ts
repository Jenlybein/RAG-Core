/**
 * 调试台「已选几个库」的摘要。
 *
 * 抽成纯函数的原因很土：这句话在两个地方出现（主面板按钮旁、弹窗里的计数），
 * 一处写 `已选 ${n} 个库`、另一处写 `已选 ${n} 个`，以后就会有人问「这两个说的是不是同一件事」。
 * 空选择必须说「未选库」而不是「已选 0 个库」——前者是一个待办状态，后者读起来像
 * 「选库这件事已经做过、结果是 0」，而实际上用户下一步就该去勾。
 */
export function selectedKbSummary(count: number): string {
  return count > 0 ? `已选 ${count} 个库` : '未选库'
}
